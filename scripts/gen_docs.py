"""Regenerate docs/protocol.md (cell table), docs/results.md (tables) and the glance table in docs/index.md from the code and data. `--check` fails if they are stale."""
import sys
sys.path.insert(0, "src")
from pathlib import Path
from seen_vs_followed import report
from seen_vs_followed.cells import BLOCKS, CELLS

ROOT = Path(__file__).resolve().parents[1]
SAYS = lambda t: f"{t[0]}→{t[1]}" if t else "–"


def protocol():
    rows = ["| cell | block | card | card asks for | typed prompt |", "|---|---|---|---|---|"]
    rows += [f"| {c['name']} | {c['block']} | {c['card']} | {SAYS(c['card_says'])} | {c['prompt'] or '(empty)'} |" for c in CELLS.values()]
    blocks = "\n".join(f"- **{k}**: {v}" for k, v in BLOCKS.items())
    return ("# Protocol\n\n<!-- generated by scripts/gen_docs.py from cells.py; do not edit by hand -->\n\n"
            "Scene: banana, Rubik's cube, bowl and bin on a table, two layouts with banana and cube swapped. "
            "Episodes alternate layouts so position cannot stand in for reading.\n\n" + blocks + "\n\n" + "\n".join(rows) + "\n")


def glance():
    rows = report.load(ROOT / "data/droid_episodes.csv")
    cols = [("Card only, empty prompt", {"R-banana", "R-cube", "R-bowl"}, "card_followed"),
            ('Card + "read the note and do what it says"', {"R-read-banana", "R-read-cube", "R-read-bowl"}, "card_followed"),
            ("Card's words typed as the prompt", {"O-banana", "O-cube", "O-bowl"}, "typed_acted")]
    head = "| policy | " + " | ".join(c[0] for c in cols) + " |\n|---|" + "---|" * len(cols)
    body = [f"| {name} | " + " | ".join(report.fmt(*report.count(rows, cells, m, policy=p)) for _, cells, m in cols) + " |"
            for p, name in report.POLICIES.items()]
    return head + "\n" + "\n".join(body)


def index():
    text = (ROOT / "docs/index.md").read_text(encoding="utf-8")
    a, b = "<!-- glance:start -->", "<!-- glance:end -->"
    return text[:text.index(a) + len(a)] + "\n" + glance() + "\n" + text[text.index(b):]


def results():
    return ("# Results\n\n<!-- generated by scripts/gen_docs.py from data/droid_episodes.csv; do not edit by hand -->\n\n"
            + report.report(report.load(ROOT / "data/droid_episodes.csv")) + "\n")


if __name__ == "__main__":
    out = {ROOT / "docs/protocol.md": protocol(), ROOT / "docs/results.md": results(), ROOT / "docs/index.md": index()}
    for p, text in out.items():
        if "--check" in sys.argv:
            assert p.exists() and p.read_text(encoding="utf-8") == text, f"{p.name} is stale: run python scripts/gen_docs.py"
        else:
            p.write_text(text, encoding="utf-8")
    print("ok")
